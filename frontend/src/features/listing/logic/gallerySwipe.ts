// Листание галереи: куда двигаться и считать ли жест листанием.
//
// Отдельно от компонента, потому что тут два правила, которые надо проверять, а не
// разглядывать: кадры ходят по кругу, и горизонтальный жест отличается от вертикальной
// прокрутки. Ошибка во втором ломает не галерею, а страницу — палец, ведущий вниз,
// перестаёт её листать.

/** Порог, ниже которого жест — не листание, а дрожание пальца при нажатии. */
export const SWIPE_THRESHOLD = 40

/** Следующий кадр по кругу: с последнего — на первый, с первого назад — на последний. */
export function nextIndex(current: number, step: number, total: number): number {
  if (total <= 0) return 0
  return (current + step + total) % total
}

/** Куда листать по жесту: -1, 1 или 0, если это не листание.
 *
 *  Горизонтальное смещение должно превышать вертикальное — иначе палец, ведущий страницу
 *  вниз по диагонали, перелистывал бы кадры и мешал прокрутке. */
export function swipeStep(deltaX: number, deltaY: number): -1 | 0 | 1 {
  if (Math.abs(deltaX) < SWIPE_THRESHOLD) return 0
  if (Math.abs(deltaX) <= Math.abs(deltaY)) return 0
  return deltaX < 0 ? 1 : -1
}
