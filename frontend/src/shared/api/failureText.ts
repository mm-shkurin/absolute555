// Перевод отказа в предложение, которое можно показать человеку.
//
// Правило одно: текст говорит, что произошло и что делать. «Ошибка 500» не сообщает
// ни того, ни другого — человек всё равно нажмёт ту же кнопку ещё раз.
import { isHttpError, isRequestTimeout } from './httpClient'

const BY_CODE: Record<string, string> = {
  LISTING_NOT_FOUND: 'Объявление не найдено — возможно, его сняли с публикации.',
  LISTING_SOLD: 'Машину уже продали. Предложение отправить нельзя.',
  OFFER_EXPIRED: 'Срок предложения истёк. Отправьте новое.',
  OFFER_ALREADY_ANSWERED: 'На это предложение уже ответили.',
  RECOGNITION_FAILED: 'Не удалось прочитать фотографию. Переснимите или заполните вручную.',
  VIN_NOT_RECOGNIZED: 'VIN не разобрали. Впишите его вручную — остальное подтянется.',
  PHOTO_LIMIT_EXCEEDED: 'Больше фотографий добавить нельзя.',
  MODERATION_REASON_REQUIRED: 'Укажите причину отклонения — продавец увидит её текстом.',
  FORBIDDEN: 'Для этого действия не хватает прав.',
}

const BY_STATUS: Record<number, string> = {
  403: 'Для этого действия не хватает прав.',
  404: 'Не нашли то, что вы открыли. Возможно, это удалили.',
  409: 'Данные успели измениться. Обновите страницу и попробуйте снова.',
  413: 'Файл слишком большой. Уменьшите размер и повторите.',
  429: 'Слишком много запросов подряд. Подождите немного.',
}

export function failureText(error: unknown): string {
  if (isRequestTimeout(error)) {
    return 'Сервер не ответил вовремя. Проверьте связь и попробуйте ещё раз.'
  }
  if (isHttpError(error)) {
    const byCode = error.errorCode ? BY_CODE[error.errorCode] : undefined
    if (byCode) return byCode
    const byStatus = BY_STATUS[error.status]
    if (byStatus) return byStatus
    // Пятисотые — это не про пользователя. Просить его что-то исправить бессмысленно,
    // поэтому текст честно говорит, что сломалось на нашей стороне.
    if (error.status >= 500) return 'Сервис временно недоступен. Мы уже знаем, попробуйте позже.'
    return error.message
  }
  // Сеть отвалилась до ответа: fetch отклоняется TypeError без статуса.
  return 'Нет связи с сервером. Проверьте интернет и повторите.'
}
