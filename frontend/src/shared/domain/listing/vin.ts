// VIN в открытой карточке показывается частично: полный номер — личные данные владельца
// и подарок тому, кто клонирует объявление вместе с историей машины. В shared, а не в
// карточке: маскирует одинаково и карточка, и очередь модерации.
export function maskVin(vin: string | null): string | null {
  if (!vin) return null
  // Слишком короткий номер маскировать нечем: от него остались бы одни точки.
  if (vin.length <= 9) return vin
  return `${vin.slice(0, 5)}${'•'.repeat(vin.length - 9)}${vin.slice(-4)}`
}
